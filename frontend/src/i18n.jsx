function interpolate(template, params = {}) {
  return template.replace(/{{\s*(\w+)\s*}}/g, (_, key) => String(params[key] ?? ''))
}

function createTranslator(language) {
  return (key, params) => {
    const dict = STRINGS[language] || STRINGS.en
    const fallback = STRINGS.en[key] || key
    const template = dict[key] || fallback
    return interpolate(template, params)
  }
}

const I18nContext = createContext({
  language: 'en',
  locale: 'en-US',
  t: createTranslator('en'),
  setLanguage: () => {},
})

export function I18nProvider({ language, setLanguage, children }) {
  const locale = language === 'de' ? 'de-DE' : 'en-US'
  const t = useMemo(() => createTranslator(language), [language])

  const value = useMemo(
    () => ({ language, locale, t, setLanguage }),
    [language, locale, t, setLanguage],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}
